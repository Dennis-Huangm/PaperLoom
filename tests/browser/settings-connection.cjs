// Run serve_settings_fixture.py first: this fixture never calls a real provider.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
    const navigateByClick = async (locator) => Promise.all([page.waitForEvent('load'), locator.click()]);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:8774/settings');
    await page.locator('[name=llm_model]').fill('fixture-model');
    await page.locator('#credential-llm_api_key').fill('fixture-key');
    await page.locator('#credential-llm_base_url').fill('https://example.test/v1');
    await page.locator('#test-model-connection').click();
    await page.waitForFunction(() => document.querySelector('#connection-test-result').textContent.includes('连接成功'));
    await page.locator('[name=llm_model]').fill('changed-model');
    assert.match(await page.locator('#connection-test-result').textContent(), /重新测试/);
    await page.locator('button[formaction="/settings/model-presets"]').click();
    await page.locator('#model-connection-form button[type=submit]:not([formaction])').first().click();
    await page.waitForURL('**/settings?saved=credentials');
    assert.equal(await page.locator('[name=llm_model]').inputValue(), 'changed-model');
    assert.equal(await page.locator('#credential-llm_api_key').inputValue(), '');
    await page.locator('#model-preset-name').fill('常用服务');
    const savePreset = page.locator('button[formaction="/settings/model-presets"]');
    await navigateByClick(savePreset);
    await page.waitForURL('**/settings?saved=model-preset#credentials');
    const firstPreset = await page.locator('#model-preset-select').inputValue();
    assert(firstPreset);
    await page.locator('[name=llm_model]').fill('local-model');
    await page.locator('[name=clear_llm_api_key]').check();
    await page.locator('#credential-llm_base_url').fill('http://localhost:11434/v1');
    await page.locator('#model-preset-name').fill('本地模型');
    await navigateByClick(savePreset);
    await page.waitForURL('**/settings?saved=model-preset#credentials');
    assert.equal(await page.locator('[name=llm_model]').inputValue(), 'local-model');
    const localPreset = await page.locator('#model-preset-select').inputValue();
    // Duplicate names keep the draft intact and show an actionable error.
    await page.locator('#model-preset-name').fill('常用服务');
    await savePreset.click();
    await page.getByText('已存在同名模型配置，请使用其他名称。', {exact: true}).waitFor();
    assert.equal(await page.locator('[name=llm_model]').inputValue(), 'local-model');
    page.on('dialog', dialog => dialog.accept());
    await page.locator('#model-preset-select').selectOption(firstPreset);
    await navigateByClick(page.locator('#model-preset-switcher button:not([formaction])'));
    await page.waitForURL('**/settings?saved=model-switched#credentials');
    assert.equal(await page.locator('[name=llm_model]').inputValue(), 'changed-model');
    await page.locator('[aria-controls=credential-llm_api_key]').click();
    await page.waitForFunction(() => document.querySelector('#credential-llm_api_key').value === 'fixture-key');
    assert.equal(await page.locator('#credential-llm_api_key').inputValue(), 'fixture-key');
    await page.locator('[aria-controls=credential-llm_api_key]').click();
    await page.locator('#model-preset-select').selectOption(localPreset);
    await navigateByClick(page.locator('#model-preset-switcher button:not([formaction])'));
    await page.waitForURL('**/settings?saved=model-switched#credentials');
    assert.equal(await page.locator('[name=llm_model]').inputValue(), 'local-model');
    assert.equal(await page.locator('#credential-llm_api_key').getAttribute('data-configured'), 'false');
    await navigateByClick(page.locator('button[formaction="/settings/model-presets/delete"]'));
    await page.waitForURL('**/settings?saved=model-deleted#credentials');
    assert.equal(await page.locator('#model-preset-select option').count(), 2);
    assert.equal(await page.locator('[name=llm_model]').inputValue(), 'local-model');
    await page.screenshot({path: process.env.SETTINGS_SCREENSHOT || 'settings-preview.png', fullPage: false});
    await page.setViewportSize({width: 390, height: 844});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    console.log('Settings desktop/mobile and test/edit/save/preset/switch/delete flows passed.');
  } finally {await browser.close();}
})().catch(error => {console.error(error); process.exitCode = 1;});
