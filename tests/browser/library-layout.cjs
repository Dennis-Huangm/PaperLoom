// Start python tests/browser/serve_library_fixture.py; all writes use disposable data.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge'});
  const page = await browser.newPage();
  const base = process.env.LIBRARY_PREVIEW_URL || 'http://127.0.0.1:8793';
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  assert.equal((await page.request.post(base + '/fixture/reset')).ok(), true);
  fs.mkdirSync('work/library-qa', {recursive: true});
  for (const width of [1920, 1440, 1024, 768, 390]) {
    await page.setViewportSize({width, height: 1000});
    await page.goto(base + '/library');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `library overflow at ${width}`);
    assert.equal(await page.locator('.saved-paper-card').count(), 5);
    assert.equal(await page.locator('.reading-editor[open]').count(), 0);
    await page.screenshot({path: `work/library-qa/library-${width}.png`, fullPage: true});
    if (width === 1440) await page.screenshot({path: 'work/library-qa/library-desktop.png'});
    const card = page.locator('.saved-paper-card').first();
    const summary = card.locator('.library-abstract .paper-summary');
    const collapsedHeight = await summary.evaluate(node => node.clientHeight);
    await card.getByRole('button', {name: '展开摘要与保存理由'}).click();
    assert((await summary.evaluate(node => node.clientHeight)) > collapsedHeight);
    await card.getByRole('button', {name: '收起摘要与保存理由'}).click();
    await card.locator('.reading-editor>summary').click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({path: `work/library-qa/reading-${width}.png`, fullPage: true});
    await card.locator('.library-more>summary').click();
    assert.equal(await card.getByRole('link', {name: '查看 arXiv 原文'}).isVisible(), true);
    assert.equal(await card.getByRole('link', {name: '打开 PDF'}).isVisible(), true);
    assert.match(await card.getByRole('link', {name: '收录与同步'}).getAttribute('href'), /2407.05600v2/);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.keyboard.press('Escape');
    assert.equal(await card.locator('.library-more').getAttribute('open'), null);
  }
  await page.setViewportSize({width: 1440, height: 1000});
  await page.goto(base + '/library');
  const count = value => page.locator(`[data-library-count="${value}"]`).textContent();
  assert.equal(await count('all'), '5');
  assert.equal(await count('unread'), '2');
  const card = page.locator('.saved-paper-card').first();
  assert.equal(await card.getByRole('link', {name: '打开论文报告'}).isVisible(), true);
  assert.match(await card.getByRole('link', {name: '阅读对话', exact: true}).getAttribute('href'), /2407.05600v2/);
  await card.locator('.reading-editor>summary').click();
  await card.getByLabel('阅读进度', {exact: true}).selectOption('read');
  await card.getByLabel('标签', {exact: true}).fill('待复现, SVG');
  await card.getByLabel('个人笔记与结论').fill('独立验证笔记 <script>example()</script>');
  await card.getByRole('button', {name: '保存阅读记录'}).click();
  await card.getByText('阅读进度与个人笔记已保存', {exact: true}).waitFor();
  assert.equal(await card.locator('.library-reading-badge').textContent(), '已读');
  assert.equal(await count('unread'), '1');
  assert.equal(await count('read'), '2');
  await page.reload();
  await card.locator('.reading-editor>summary').click();
  assert.equal(await card.getByLabel('个人笔记与结论').inputValue(), '独立验证笔记 <script>example()</script>');
  assert.equal(await card.locator('script').count(), 0);
  const form = card.locator('.reading-form');
  const expected = await form.locator('[name="expected_updated_at"]').inputValue();
  const profile = await page.locator('body').getAttribute('data-profile-id');
  const external = await page.request.post(base + '/api/library/reading', {form: {
    profile_id: profile, arxiv_id: '2407.05600', reading_status: 'read', notes: '在另一页面保存',
    tags: '', read_version: '2', expected_updated_at: expected}});
  assert.equal(external.status(), 200);
  await card.getByLabel('个人笔记与结论').fill('保留这份尚未保存的修改');
  await card.getByRole('button', {name: '保存阅读记录'}).click();
  await card.getByText(/阅读记录已在其他页面修改/).waitFor();
  assert.equal(await card.getByLabel('个人笔记与结论').inputValue(), '保留这份尚未保存的修改');

  await page.locator('.library-status-tabs').getByRole('link', {name: /^已读/}).click();
  assert.equal(await page.locator('.saved-paper-card').count(), 2);
  await page.getByRole('searchbox').fill('SVG');
  await page.getByRole('button', {name: '搜索', exact: true}).click();
  assert.equal(new URL(page.url()).searchParams.get('reading_status'), 'read');
  await page.locator('.library-status-tabs').getByRole('link', {name: /^阅读中/}).click();
  assert.equal(new URL(page.url()).searchParams.get('q'), 'SVG');
  await page.getByRole('link', {name: '清除搜索', exact: true}).click();
  assert.equal(new URL(page.url()).searchParams.get('reading_status'), 'reading');
  await page.getByRole('link', {name: '清除筛选', exact: true}).click();
  await page.getByRole('searchbox').fill('no-match-zzzz');
  await page.getByRole('button', {name: '搜索', exact: true}).click();
  await page.getByRole('heading', {name: '没有匹配的已保存论文'}).waitFor();
  await page.getByRole('link', {name: '查看全部论文'}).click();
  const last = page.locator('.saved-paper-card').last();
  assert.equal(await last.getByRole('button', {name: '生成论文报告'}).isVisible(), true);
  assert.equal(await last.locator('.library-chat-disabled').getAttribute('aria-disabled'), 'true');
  await last.locator('.library-more>summary').click();
  page.once('dialog', dialog => dialog.dismiss());
  await last.getByRole('button', {name: '移出文献库'}).click();
  assert.equal(await page.locator('.saved-paper-card').count(), 5);
  page.once('dialog', dialog => dialog.accept());
  await last.getByRole('button', {name: '移出文献库'}).click();
  await page.waitForFunction(() => document.querySelectorAll('.saved-paper-card').length === 4);
  assert.equal(await count('all'), '4');
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('Library responsive previews, menus, durable notes and progress, conflict retention, filtering and removal passed.');
})().catch(error => {console.error(error); process.exit(1);});
